#!/usr/bin/env node
// Normalise real circuit outlines into a 200x120 box for the F1 page.
//   node scripts/build-circuits.mjs   ->  src/data/circuits.ts
import fs from "node:fs";
import path from "node:path";
import svgpath from "svgpath";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const src = JSON.parse(fs.readFileSync(path.join(root, "scripts/circuits.json"), "utf8"));
const W = 200, H = 120, PAD = 10;

function bbox(p) {
  // sample every segment so curves don't overshoot the box
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  let cx = 0, cy = 0;
  const hit = (x, y) => { minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y); };
  p.iterate((seg) => {
    const [c, ...n] = seg;
    if (c === "M" || c === "L") { cx = n[0]; cy = n[1]; hit(cx, cy); }
    else if (c === "C") {
      const [x1, y1, x2, y2, x, y] = n;
      for (let t = 0; t <= 1; t += 0.05) {
        const mt = 1 - t;
        hit(mt ** 3 * cx + 3 * mt ** 2 * t * x1 + 3 * mt * t ** 2 * x2 + t ** 3 * x,
            mt ** 3 * cy + 3 * mt ** 2 * t * y1 + 3 * mt * t ** 2 * y2 + t ** 3 * y);
      }
      cx = x; cy = y;
    }
  });
  return { minX, minY, maxX, maxY };
}

const out = {};
for (const [slug, c] of Object.entries(src)) {
  if (slug.startsWith("_")) continue;
  let p = svgpath(c.d);
  if (c.transform) p = p.transform(c.transform);
  p = p.abs().unshort().unarc();
  const b = bbox(p);
  const s = Math.min((W - 2 * PAD) / (b.maxX - b.minX), (H - 2 * PAD) / (b.maxY - b.minY));
  const dx = (W - (b.maxX - b.minX) * s) / 2 - b.minX * s;
  const dy = (H - (b.maxY - b.minY) * s) / 2 - b.minY * s;
  out[slug] = svgpath(p.toString()).scale(s).translate(dx, dy).round(1).toString();
  console.log(slug.padEnd(12), `${Math.round((b.maxX - b.minX) * s)}x${Math.round((b.maxY - b.minY) * s)}`, `${out[slug].length} chars`);
}

const ts = `// Generated by scripts/build-circuits.mjs from scripts/circuits.json. Do not edit by hand.
// Outlines derive from Wikimedia Commons track maps (CC BY-SA); see circuits.json for sources.
export const circuits: Record<string, string> = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync(path.join(root, "src/data/circuits.ts"), ts);
console.log("wrote src/data/circuits.ts");
